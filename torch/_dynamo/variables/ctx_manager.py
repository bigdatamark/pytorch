class ContextWrappingVariable(VariableTracker):
    # [CLASS DOC] Base tracker for a context manager whose effect is a global
    # state change. State: target_values (state applied on enter; None or a
    # sequence), initial_values (state restored on exit), cleanup_fn (the pending
    # restore callback, cleared once run). Subclasses supply a _call_func that
    # applies a value list, module_name/fn_name used to reconstruct the manager
    # in generated bytecode, and may override enter/exit. enter applies the
    # target state eagerly and registers a cleanup hook on the output graph so
    # the state is restored after tracing; exit runs the cleanup once.
    _nonvar_fields = {
        "cm_obj",
        "target_values",
        "initial_values",
        "state",
        *VariableTracker._nonvar_fields,
    }

    def __init__(
        self, target_values: Any, initial_values: Any | None = None, **kwargs: Any
    ) -> None:
        # [FUNCTION DOC] Store target and initial values. Raises TypeError if
        # target_values is neither None nor a sequence.
        super().__init__(**kwargs)
        self.target_values = target_values
        self.initial_values = initial_values
        # target_values must be None or a Sequence for reconstruct / _call_func
        # etc. to work properly.
        if not (target_values is None or isinstance(target_values, Sequence)):
            raise TypeError(
                "ContextWrappingVariable.target_values must be None or a "
                f"Sequence, got {type(target_values).__name__}"
            )

    def tp_richcompare_impl(
        self, tx: "InstructionTranslatorBase", other: VariableTracker, op: str
    ) -> VariableTracker:
        # [FUNCTION DOC] Rich comparison using the default object comparison rules.
        from .object_protocol import object_richcompare

        return object_richcompare(self, tx, other, op)

    def enter(self, tx: "InstructionTranslatorBase") -> VariableTracker:
        # [FUNCTION DOC] Enter the context: if the subclass defines _call_func,
        # apply the target values; register the default cleanup hook. Returns a
        # None constant. Side effect: mutates global state via _call_func.
        if hasattr(self, "_call_func"):
            self._call_func(tx, self.target_values)
        self.set_cleanup_hook(tx)
        return variables.ConstantVariable.create(None)

    def set_cleanup_hook(
        self, tx: "InstructionTranslatorBase", fn: Callable[..., Any] | None = None
    ) -> None:
        # [FUNCTION DOC] Record the cleanup callback in cleanup_fn and register
        # this variable's cleanup method with the output graph so it runs when
        # compilation of the graph finishes. Default callback re-applies the
        # initial values via _call_func if defined.
        if fn is None:

            def fn() -> None:
                # [FUNCTION DOC] HELPER: default cleanup; restore initial values
                # through _call_func when the subclass defines it.
                if hasattr(self, "_call_func"):
                    self._call_func(tx, self.initial_values)

        self.cleanup_fn: Callable[..., Any] | None = fn
        tx.output.add_cleanup_hook(self.cleanup)

    def exit(
        self, tx: "InstructionTranslatorBase", *args: VariableTracker
    ) -> VariableTracker:
        # [FUNCTION DOC] Exit the context: runs the cleanup (asserting it had not
        # already run). Returns a None constant. Exception args are ignored.
        self.cleanup_assert()
        return variables.ConstantVariable.create(None)

    def reconstruct_type(self, codegen: "PyCodegen") -> None:
        # [FUNCTION DOC] Emit bytecode that loads the context manager class, via
        # an attribute of the module named by module_name/fn_name.
        codegen(
            AttrSource(codegen.tx.import_source(self.module_name()), self.fn_name())
        )

    def reconstruct(self, codegen: "PyCodegen") -> None:
        # [FUNCTION DOC] Emit bytecode that recreates the context manager: load
        # the class, push each target value as a constant, and call it with that
        # many arguments (no arguments when target_values is empty or None).
        codegen.add_push_null(lambda: self.reconstruct_type(codegen))
        target_values = self.target_values
        if not target_values:
            target_values = ()
        codegen.extend_output([codegen.create_load_const(val) for val in target_values])
        codegen.extend_output(create_call_function(len(target_values), False))

    def module_name(self) -> str:
        # [FUNCTION DOC] Module that holds the real context manager class; must be
        # overridden. Base raises NotImplementedError.
        raise NotImplementedError("module_name called on base")

    def fn_name(self) -> str:
        # [FUNCTION DOC] Name of the real context manager class/function; must be
        # overridden. Base raises NotImplementedError.
        raise NotImplementedError("fn_name called on base")

    def call_function(
        self,
        tx: "InstructionTranslatorBase",
        args: list[VariableTracker],
        kwargs: dict[str, VariableTracker],
    ) -> VariableTracker:
        # [FUNCTION DOC] Use the context manager as a decorator: requires exactly
        # one positional argument that is a user function, nested function,
        # method or skip-function variable (assertion error otherwise) and returns
        # the matching Wrapped* variable binding this context manager to it.
        # kwargs are ignored.
        if len(args) != 1:
            raise AssertionError(f"expected exactly 1 arg, got {len(args)}")
        if not isinstance(
            args[0],
            (
                NestedUserFunctionVariable,
                SkipFunctionVariable,
                UserMethodVariable,
                UserFunctionVariable,
            ),
        ):
            raise AssertionError(f"expected a function variable, got {type(args[0])}")

        if isinstance(args[0], NestedUserFunctionVariable):
            return WrappedNestedUserFunctionVariable(args[0], self)
        elif isinstance(args[0], SkipFunctionVariable):
            return WrappedSkipFunctionVariable(args[0], self)
        elif isinstance(args[0], UserMethodVariable):
            return WrappedUserMethodVariable(args[0], self)
        elif isinstance(args[0], UserFunctionVariable):
            return WrappedUserFunctionVariable(args[0], self)
        else:
            raise AssertionError("Unexpected arg type")

    def supports_graph_breaks(self) -> bool:
        # [FUNCTION DOC] True: graph breaks inside the with block are supported
        # (the context is reconstructed in the resume function).
        return True

    def exit_on_graph_break(self) -> bool:
        # [FUNCTION DOC] True: the context is exited when a graph break happens.
        return True

    def cleanup(self) -> None:
        # [FUNCTION DOC] Run the pending cleanup callback once and clear it; no-op
        # if nothing is pending.
        if self.cleanup_fn is not None:
            self.cleanup_fn()
            self.cleanup_fn = None

    def cleanup_assert(self) -> None:
        # [FUNCTION DOC] Like cleanup but raises an assertion error if no cleanup
        # is pending (meaning exit was called twice or enter never ran).
        if not self.cleanup_fn:
            raise AssertionError("multiple exits?")
        self.cleanup()


class GenericContextWrappingVariable(UserDefinedObjectVariable):
    # [CLASS DOC] Tracker for an arbitrary user context manager object whose
    # __enter__/__exit__ are traced (inlined) as user methods rather than applied
    # as global state changes. State: cm_obj, the real context manager. It does
    # not support graph breaks inside its with block; exit pops the translator's
    # active generic context manager stack.
    # Some methods in ContextWrappingVariable assumes the arguments are
    # python constants. Which might not always be the case here.
    def __init__(self, cm_obj: AbstractContextManager[Any], **kwargs: Any) -> None:
        # [FUNCTION DOC] Wrap cm_obj (must not be None, else assertion error) as a
        # user-defined object of its own class and remember it in cm_obj.
        if cm_obj is None:
            raise AssertionError("cm_obj must not be None")
        super().__init__(
            value=cm_obj,
            value_type=cm_obj.__class__,
            **kwargs,
        )
        self.cm_obj = cm_obj

    def module_name(self) -> str:
        # [FUNCTION DOC] Module of the wrapped manager's class.
        return self.cm_obj.__module__

    def fn_name(self) -> str:
        # [FUNCTION DOC] Class name of the wrapped manager.
        return type(self.cm_obj).__name__

    def enter(self, tx: "InstructionTranslatorBase") -> VariableTracker:
        # [FUNCTION DOC] Trace a call of the object's enter method (as a bound
        # user method with no args, sourced from the enter attribute when this
        # variable has a source). Returns the traced result.
        source = None if self.source is None else AttrSource(self.source, "__enter__")
        return variables.UserMethodVariable(
            self.cm_obj.__enter__.__func__,  # type: ignore[attr-defined]
            self,
            source=source,
        ).call_function(tx, [], {})

    def exit(
        self, tx: "InstructionTranslatorBase", *args: VariableTracker
    ) -> VariableTracker:
        # [FUNCTION DOC] Trace a call of the object's exit method with the given
        # exception args, then pop the translator's active generic context manager
        # stack. Returns the traced result.
        source = None if self.source is None else AttrSource(self.source, "__exit__")
        x = variables.UserMethodVariable(
            self.cm_obj.__exit__.__func__,  # type: ignore[attr-defined]
            self,
            source=source,
        ).call_function(tx, list(args), {})
        tx.active_generic_context_managers.pop()
        return x

    def supports_graph_breaks(self) -> bool:
        # [FUNCTION DOC] False: graph breaks inside the block are not supported.
        return False

    def exit_on_graph_break(self) -> bool:
        # [FUNCTION DOC] True: exited when a graph break happens.
        return True


class RecordFunctionVariable(GenericContextWrappingVariable):
    # [CLASS DOC] Tracker for a torch.profiler record_function object used as a
    # generic context manager. State: record_fn, a profiler record-function
    # context variable built from the object's name and args; enter and exit
    # delegate to it while maintaining the active generic context manager stack.
    def __init__(self, cm_obj: torch.profiler.record_function, **kwargs: Any) -> None:
        # [FUNCTION DOC] Wrap the record_function object and build record_fn from
        # its name and (if set) args as constants.
        super().__init__(cm_obj, **kwargs)
        args = [variables.ConstantVariable.create(cm_obj.name)]
        record_kwargs = {}
        if cm_obj.args:
            record_kwargs["args"] = variables.ConstantVariable.create(cm_obj.args)
        self.record_fn = variables.torch.ProfilerRecordFunctionContextVariable.create(
            func=type(self.cm_obj), record_args=args, record_kwargs=record_kwargs
        )

    def enter(self, tx):
        # [FUNCTION DOC] Push self on the active generic context manager stack and
        # enter record_fn; returns its result.
        tx.active_generic_context_managers.append(self)
        return self.record_fn.enter(tx)

    def exit(self, tx, *args):
        # [FUNCTION DOC] Pop the active generic context manager stack and exit
        # record_fn with the given args; returns its result.
        tx.active_generic_context_managers.pop()
        return self.record_fn.exit(tx, *args)


class RepararametrizeModuleContextVariable(GenericContextWrappingVariable):
    # [CLASS DOC] Wrapper for a module reparametrization context manager.
    # State: cm_vt (the wrapped context manager variable), mod (module variable),
    # and, after enter, the realized parameters/buffers dict variables. It does
    # not initialize the base class; unknown attributes are forwarded to cm_vt.
    # While active, mutations on the module's parameters and buffers dicts are
    # ignored by the side-effect tracker.
    def __init__(self, ctx_manager_vt: ContextWrappingVariable, mod: Any) -> None:
        # [FUNCTION DOC] Remember the wrapped context manager variable and module.
        # KNOWN ISSUE: deliberately skips the base initializer, so base fields are
        # only available through attribute forwarding to the wrapped variable.
        self.cm_vt = ctx_manager_vt
        self.mod = mod
        # We don't call super().__init__() because we're delegating most methods to cm_vt

    def enter(self, tx: "InstructionTranslatorBase") -> VariableTracker:
        # [FUNCTION DOC] Within a mode allowing side effects in the higher-order
        # op: realize the module's parameters and buffers dict variables, tell the
        # side-effect tracker to ignore mutations on them, then enter the wrapped
        # context manager and return its result.
        # Custom enter implementation with side effects. Additionally, do not
        # worry about side effects for the hop, as they cancel each other out.
        with torch._dynamo.variables.higher_order_ops.dynamo_allow_side_effects_in_hop(
            tx
        ):
            self.old_parameters_var = self.mod.tp_getattro_impl(
                tx, "_parameters"
            ).realize()
            self.old_buffer_var = self.mod.tp_getattro_impl(tx, "_buffers").realize()
            tx.output.side_effects.ignore_mutations_on(self.old_parameters_var)
            tx.output.side_effects.ignore_mutations_on(self.old_buffer_var)
            return self.cm_vt.enter(tx)

    def exit(
        self, tx: "InstructionTranslatorBase", *args: VariableTracker
    ) -> VariableTracker:
        # [FUNCTION DOC] Within the same side-effect-allowing mode: exit the
        # wrapped context manager, then stop ignoring mutations on the buffers and
        # parameters dict variables recorded in enter. Returns the exit result.
        # Custom enter implementation with side effects. Additionally, do not
        # worry about side effects for the hop, as they cancel each other out.
        with torch._dynamo.variables.higher_order_ops.dynamo_allow_side_effects_in_hop(
            tx
        ):
            x = self.cm_vt.exit(tx, *args)
            tx.output.side_effects.stop_ignoring_mutations_on(self.old_buffer_var)
            tx.output.side_effects.stop_ignoring_mutations_on(self.old_parameters_var)
            return x

    # Forward all other method calls to self.cm_vt
    def __getattr__(self, name: str) -> Any:
        # [FUNCTION DOC] Forward any attribute not found on this object to the
        # wrapped context manager variable.
        # This will be called for any attribute not explicitly defined in this class
        return getattr(self.cm_vt, name)


class GradInplaceRequiresGradCtxManagerVariable(ContextWrappingVariable):
    # [CLASS DOC] Models the functorch switch controlling whether in-place ops may
    # set requires_grad. Enter sets the flag eagerly (remembering the previous
    # value in prev_state), emits a graph node setting it, and registers cleanup
    # restoring it; exit restores it and emits the restoring node.
    """represents torch grad requires grad"""

    @staticmethod
    def create(
        tx: "InstructionTranslatorBase", target_values: Any, **kwargs: Any
    ) -> "GradInplaceRequiresGradCtxManagerVariable":
        # [FUNCTION DOC] Factory: build the variable with the given target values
        # (a one-element sequence holding the enabled flag) and no initial values.
        return GradInplaceRequiresGradCtxManagerVariable(
            target_values=target_values,
            initial_values=None,
            **kwargs,
        )

    def enter(self, tx: "InstructionTranslatorBase") -> VariableTracker:
        # [FUNCTION DOC] Save the current flag, set it to the target value, register
        # cleanup to restore it, and add a graph node performing the set. Returns
        # a None constant. Side effect: changes functorch global state.
        [enabled] = self.target_values
        self.prev_state = torch._C._functorch.get_inplace_requires_grad_allowed()
        torch._C._functorch.set_inplace_requires_grad_allowed(enabled)
        self.set_cleanup_hook(
            tx,
            lambda: torch._C._functorch.set_inplace_requires_grad_allowed(
                self.prev_state
            ),
        )
        self.proxy = tx.output.create_node(
            "call_function",
            torch._C._functorch.set_inplace_requires_grad_allowed,
            (enabled,),
            {},
        )
        return variables.ConstantVariable.create(None)

    def exit(
        self, tx: "InstructionTranslatorBase", *args: VariableTracker
    ) -> VariableTracker:
        # [FUNCTION DOC] Run cleanup (restores the saved flag) and add a graph node
        # that restores it. Returns a None constant.
        self.cleanup()
        tx.output.create_node(
            "call_function",
            torch._C._functorch.set_inplace_requires_grad_allowed,
            (self.prev_state,),
            {},
        )
        return variables.ConstantVariable.create(None)


