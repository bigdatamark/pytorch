class CudagraphOverrideVariable(ContextWrappingVariable):
    # [CLASS DOC] Models the cudagraph override manager. target_values is the
    # (forward, backward) flag pair; initial_values is captured on enter from the
    # output graph's current annotation. The annotation is stored on the output
    # graph and tracing context. It persists across graph breaks (exit does not
    # clean up; cleanup is deferred to graph compilation).
    """represents torch._dynamo.override_cudagraphs"""

    def __init__(self, fwd: bool | None, bwd: bool | None, **kwargs: Any) -> None:
        # [FUNCTION DOC] Store (fwd, bwd) as target values; initial values are
        # filled in on enter.
        super().__init__(
            target_values=(fwd, bwd),
            initial_values=None,  # Captured in enter()
            **kwargs,
        )

    def enter(self, tx: "InstructionTranslatorBase") -> "VariableTracker":
        # [FUNCTION DOC] Capture the current annotation as initial values (its fwd
        # and bwd pair, or a single None meaning no annotation), then run the base
        # enter which applies the target and registers cleanup.
        # Capture current annotation before overwriting
        prev = tx.output.cudagraph_annotation
        if prev is not None:
            self.initial_values = (prev.fwd, prev.bwd)
        else:
            self.initial_values = (None,)
        return super().enter(tx)

    def _call_func(
        self, tx: "InstructionTranslatorBase", values: tuple[Any, ...]
    ) -> None:
        # [FUNCTION DOC] HELPER: apply values to the output graph and tracing
        # context. A single None clears the annotation; otherwise values must be
        # exactly two (assertion error otherwise) and a new annotation with those
        # forward and backward flags is stored.
        from torch._inductor import _CudagraphAnnotation

        if len(values) == 1 and values[0] is None:
            # Restoring to no annotation
            tx.output.cudagraph_annotation = None
            tx.output.tracing_context.cudagraph_annotation = None
        else:
            if len(values) != 2:
                raise AssertionError(f"expected 2 values, got {len(values)}")
            fwd, bwd = values
            annotation = _CudagraphAnnotation(fwd=fwd, bwd=bwd)
            tx.output.cudagraph_annotation = annotation
            tx.output.tracing_context.cudagraph_annotation = annotation

    def module_name(self) -> str:
        # [FUNCTION DOC] Module used when reconstructing: torch._dynamo.
        return "torch._dynamo"

    def fn_name(self) -> str:
        # [FUNCTION DOC] Reconstruction name: override_cudagraphs.
        return "override_cudagraphs"

    def python_type(self) -> type:
        # [FUNCTION DOC] The Python type reported: the cudagraph override context
        # manager class.
        from torch._dynamo.decorators import CudagraphOverrideContextManager

        return CudagraphOverrideContextManager

    def exit_on_graph_break(self) -> bool:
        # [FUNCTION DOC] False: the manager is not exited on graph break; each
        # resume function re-enters it.
        # Annotation persists until graph is compiled; each resume function
        # will reconstruct the context manager and call enter() again
        return False

    def exit(
        self, tx: "InstructionTranslatorBase", *args: VariableTracker
    ) -> "VariableTracker":
        # [FUNCTION DOC] Does not run cleanup (deferred to the cleanup hooks during
        # graph compilation, after the annotation is copied to graph metadata).
        # Returns a None constant.
        # Override to NOT call cleanup here. The cleanup will happen in
        # call_cleanup_hooks() during compile_subgraph, which is AFTER
        # the annotation is copied to gm.meta.
        return variables.ConstantVariable.create(None)


class WithEnterFunctionVariable(VariableTracker):
    # [CLASS DOC] Stand-in for the bound enter method of a context manager seen by
    # the translator at a with statement. State: ctx, the context manager variable.
    # Calling it (no args) enters the context via the translator; it reports a
    # method type and cannot be reconstructed.
    def __init__(
        self,
        ctx: ContextWrappingVariable | GenericContextWrappingVariable,
        **kwargs: Any,
    ) -> None:
        # [FUNCTION DOC] Store the context manager variable.
        super().__init__(**kwargs)
        self.ctx = ctx

    def tp_richcompare_impl(
        self, tx: "InstructionTranslatorBase", other: VariableTracker, op: str
    ) -> VariableTracker:
        # [FUNCTION DOC] Rich comparison using the default object comparison rules.
        from .object_protocol import object_richcompare

        return object_richcompare(self, tx, other, op)

    def python_type(self) -> type:
        # [FUNCTION DOC] The Python type reported: the bound method type.
        return types.MethodType

    def call_function(
        self,
        tx: "InstructionTranslatorBase",
        args: list[VariableTracker],
        kwargs: dict[str, VariableTracker],
    ) -> VariableTracker:
        # [FUNCTION DOC] Must be called with no args and no kwargs (assertion errors
        # otherwise). Asks the translator to enter the context, passing the current
        # instruction (assumed to be followed immediately by the first instruction
        # of the block); returns the translator's result.
        if args:
            raise AssertionError(
                "WithEnterFunctionVariable.call_function expects no args"
            )
        if kwargs:
            raise AssertionError(
                "WithEnterFunctionVariable.call_function expects no kwargs"
            )
        # NOTE: we assume that the instruction immediately after the current CALL instruction
        # is the first instruction of the block.

        return tx.enter_ctx(self.ctx, tx.current_instruction)

    def reconstruct(self, codegen: "PyCodegen") -> None:
        # [FUNCTION DOC] Always triggers a graph break (unimplemented): reconstructing
        # the enter method means a graph break happened inside the with setup. The
        # message names the context manager type if its module and name are
        # available.
        try:
            type_str = f"{self.ctx.module_name()}.{self.ctx.fn_name()}"
        except NotImplementedError:
            type_str = str(type(self.ctx))
        unimplemented(
            gb_type="Attempted to reconstruct context manager's __enter__ method",
            context=str(self.ctx),
            explanation=f"Attempted to reconstruct context manager {type_str} while tracing `with ...:`",
            hints=[
                "It is likely there is a graph break while tracing `with ctx:` "
                "but outside the actual `ctx.__enter__()` method. "
                "`torch.compile` does not expect this to happen.",
                *graph_break_hints.DIFFICULT,
                *graph_break_hints.DYNAMO_BUG,
            ],
        )


class WithExitFunctionVariable(VariableTracker):
    # [CLASS DOC] Stand-in for the bound exit method of a context manager that the
    # translator keeps on its stack for a with block. State: ctx (a context
    # wrapping variable; checked in the initializer) and target (the block's
    # target instruction). Calling it exits the context; reconstructing it
    # rebuilds the context manager type (the resume function re-enters).
    _nonvar_fields = {
        "target",
        *VariableTracker._nonvar_fields,
    }

    def tp_richcompare_impl(
        self, tx: "InstructionTranslatorBase", other: VariableTracker, op: str
    ) -> VariableTracker:
        # [FUNCTION DOC] Rich comparison using the default object comparison rules.
        from .object_protocol import object_richcompare

        return object_richcompare(self, tx, other, op)

    def __init__(
        self,
        ctx: ContextWrappingVariable | GenericContextWrappingVariable,
        target: Any,
        **kwargs: Any,
    ) -> None:
        # [FUNCTION DOC] Store ctx (assertion error unless it is a context wrapping
        # or generic context wrapping variable) and the target.
        super().__init__(**kwargs)
        if not isinstance(
            ctx, (ContextWrappingVariable, GenericContextWrappingVariable)
        ):
            raise AssertionError(
                f"ctx must be a ContextWrappingVariable or GenericContextWrappingVariable, got {type(ctx)}"
            )
        self.ctx = ctx
        self.target = target

    def python_type(self) -> type:
        # [FUNCTION DOC] The Python type reported: the bound method type.
        return types.MethodType

    def call_function(
        self,
        tx: "InstructionTranslatorBase",
        args: list[VariableTracker],
        kwargs: dict[str, VariableTracker],
    ) -> VariableTracker:
        # [FUNCTION DOC] Exit the context, passing the call args (exception info);
        # kwargs must be empty (assertion error otherwise). Returns the exit result.
        if kwargs:
            raise AssertionError(
                "WithExitFunctionVariable.call_function expects no kwargs"
            )
        return self.ctx.exit(tx, *args)

    def reconstruct(self, codegen: "PyCodegen") -> None:
        # [FUNCTION DOC] Emit bytecode for the context manager's type rather than its
        # exit method; the handler generated for the block re-enters the context in
        # the resume function.
        # Note here we reconstruct the context manager rather than the
        # exit function.  The handler generated by BlockStackEntry
        # will re-enter the context in the resume function.
        self.ctx.reconstruct_type(codegen)  # type: ignore[union-attr]
