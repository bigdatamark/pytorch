class CatchWarningsCtxManagerVariable(ContextWrappingVariable):
    # [CLASS DOC] Delays creation of a warnings catch_warnings manager until enter.
    # State: catch_warnings_args, a mapping from keyword name to variable.
    # Enter builds the real manager from the constant-valued args, enters it
    # eagerly and registers cleanup that exits it; reconstruct rebuilds the call
    # with keyword arguments.
    """Delay a call to warnings.catch_warnings"""

    @staticmethod
    def create(
        tx: "InstructionTranslatorBase", catch_warnings_args: dict[str, VariableTracker]
    ) -> "CatchWarningsCtxManagerVariable":
        # [FUNCTION DOC] Factory from a mapping of keyword args to variables; no
        # target or initial values.
        return CatchWarningsCtxManagerVariable(
            catch_warnings_args=catch_warnings_args,
            target_values=None,
            initial_values=None,
        )

    def __init__(
        self,
        catch_warnings_args: dict[str, VariableTracker],
        target_values: Any | None = None,
        initial_values: Any | None = None,
        **kwargs: Any,
    ) -> None:
        # [FUNCTION DOC] Store the keyword args mapping; raises an assertion error
        # if it is not a dict.
        if not isinstance(catch_warnings_args, dict):
            raise AssertionError(
                f"catch_warnings_args must be a dict, got {catch_warnings_args}"
            )
        super().__init__(
            target_values=target_values, initial_values=initial_values, **kwargs
        )
        self.catch_warnings_args = catch_warnings_args

    def enter(self, tx: "InstructionTranslatorBase") -> VariableTracker:
        # [FUNCTION DOC] Convert the keyword args to Python constants (raises
        # NotImplementedError if any is not constant), build the real manager,
        # register cleanup calling its exit, enter it, and return its enter result
        # wrapped as a variable. Side effect: modifies the global warnings filters.
        kwargs = {
            k: v.as_python_constant() for k, v in self.catch_warnings_args.items()
        }
        ctx_val = warnings.catch_warnings(**kwargs)
        self.set_cleanup_hook(tx, lambda: ctx_val.__exit__(None, None, None))
        return variables.VariableTracker.build(tx, ctx_val.__enter__())

    def reconstruct(self, codegen: "PyCodegen") -> None:
        # [FUNCTION DOC] Emit bytecode loading the catch_warnings class, pushing the
        # stored arg variables, and calling it with those names as keywords.
        codegen.add_push_null(
            lambda: codegen.load_import_from("warnings", "catch_warnings")
        )
        codegen.foreach(self.catch_warnings_args.values())
        keys = tuple(self.catch_warnings_args.keys())
        codegen.extend_output(codegen.create_call_function_kw(len(keys), keys, False))

    def python_type(self) -> type:
        # [FUNCTION DOC] The Python type reported: the catch_warnings class.
        return warnings.catch_warnings


