class GradModeVariable(ContextWrappingVariable):
    # [CLASS DOC] Models no_grad, enable_grad and set_grad_mode. target_values and
    # initial_values are one-element lists holding the grad mode flag. A shared
    # grad-mode guard is installed at construction. Setting the mode coalesces:
    # a graph node and the eager global change happen only if the mode differs.
    """represents torch.{no_grad,enable_grad,set_grad_mode}()"""

    _guards_singleton = Guard(GlobalStateSource(), GuardBuilder.GRAD_MODE)  # type: ignore[arg-type]

    @staticmethod
    def create(
        tx: "InstructionTranslatorBase",
        target_value: Any,
        initialized: bool = False,
        **kwargs: Any,
    ) -> "GradModeVariable":
        # [FUNCTION DOC] Factory: records the current grad mode as the initial
        # value and the given flag as the target. If initialized is true, applies
        # the target immediately (mimicking eager set_grad_mode, which acts at
        # construction).
        var = GradModeVariable(
            target_values=[target_value],
            initial_values=[torch.is_grad_enabled()],
            **kwargs,
        )
        if initialized:
            var._call_func(tx, var.target_values)
        return var

    def __init__(
        self,
        target_values: Any,
        initial_values: Sequence[bool] | None = None,
        initialized: bool = True,
        **kwargs: Any,
    ) -> None:
        # [FUNCTION DOC] Store the values and install the grad mode guard.
        # KNOWN ISSUE: the initialized parameter is accepted but never used here.
        super().__init__(
            target_values=target_values, initial_values=initial_values, **kwargs
        )
        install_guard(self._guards_singleton)

    def enter(self, tx: "InstructionTranslatorBase") -> VariableTracker:
        # [FUNCTION DOC] Apply the target grad mode. Returns a None constant.
        self._call_func(tx, self.target_values)
        return variables.ConstantVariable.create(None)

    def exit(
        self, tx: "InstructionTranslatorBase", *args: VariableTracker
    ) -> VariableTracker:
        # [FUNCTION DOC] Restore the initial grad mode. Returns a None constant.
        self._call_func(tx, self.initial_values)
        return variables.ConstantVariable.create(None)

    def call_function(
        self,
        tx: "InstructionTranslatorBase",
        args: list[VariableTracker],
        kwargs: dict[str, VariableTracker],
    ) -> VariableTracker:
        # [FUNCTION DOC] Use as a decorator: first restore the initial mode (undo
        # the eager change done at creation), then wrap the function via the base
        # implementation.
        self._call_func(tx, self.initial_values)  # undo eager initialization
        return super().call_function(tx, args, kwargs)

    def _call_func(self, tx: "InstructionTranslatorBase", values: Any) -> None:
        # [FUNCTION DOC] HELPER: set grad mode to the single flag in values (assertion
        # error unless exactly one value). Only when it differs from the current
        # mode: adds a graph node setting grad mode and sets it globally.
        if len(values) != 1:
            raise AssertionError(f"expected 1 value, got {len(values)}")
        value = values[0]
        # Coalesce grad mode mutations
        if torch.is_grad_enabled() != value:
            tx.output.create_node(
                "call_function", torch._C._set_grad_enabled, (value,), {}
            )
            torch._C._set_grad_enabled(value)

    def module_name(self) -> str:
        # [FUNCTION DOC] Module used when reconstructing: torch.
        return "torch"

    def fn_name(self) -> str:
        # [FUNCTION DOC] Reconstruction name: the set-grad-enabled function.
        return "set_grad_enabled"

    def python_type(self) -> type:
        # [FUNCTION DOC] The Python type reported: the set_grad_enabled class.
        return torch.set_grad_enabled


class InferenceModeVariable(ContextWrappingVariable):
    # [CLASS DOC] Models torch.inference_mode. target_values is a one-element list
    # with the mode flag; initial_values is the inference mode state at creation.
    # Enter either enters inference mode or, when the config disables inference
    # mode during fake-tensor tracing and the target is on, only disables grad.
    # Exit adds a graph node exiting inference mode.
    @staticmethod
    def create(
        tx: "InstructionTranslatorBase", target_value: Any, **kwargs: Any
    ) -> "InferenceModeVariable":
        # [FUNCTION DOC] Factory: target is the given flag; initial value is the
        # current inference mode state.
        var = InferenceModeVariable(
            [target_value], initial_values=torch.is_inference_mode_enabled(), **kwargs
        )
        return var

    def __init__(
        self,
        target_values: Any,
        initial_values: bool | None = None,
        **kwargs: Any,
    ) -> None:
        # [FUNCTION DOC] If initial_values is None, query the current inference mode
        # state at call time (defaults cannot do this at import time).
        if initial_values is None:
            # This must be called here since function defaults are evaluated at import time
            initial_values = torch.is_inference_mode_enabled()
        super().__init__(
            target_values=target_values, initial_values=initial_values, **kwargs
        )

    def exit(
        self, tx: "InstructionTranslatorBase", *args: VariableTracker
    ) -> VariableTracker:
        # [FUNCTION DOC] Run the pending cleanup (assert it exists) and add a graph
        # node exiting inference mode using the enter node. Returns a None constant.
        self.cleanup_assert()
        tx.output.create_node(
            "call_function",
            torch.autograd.grad_mode._exit_inference_mode,
            (self.proxy,),
            {},
        )
        return variables.ConstantVariable.create(None)

    def enter(self, tx: "InstructionTranslatorBase") -> VariableTracker:
        # [FUNCTION DOC] If the dynamo config disables inference mode for fake
        # tensors and the target is on, record the prior grad mode and only turn
        # grad off; otherwise enter inference mode and keep its context. Registers
        # cleanup (restore grad mode, or exit inference mode) and adds a graph node
        # entering inference mode. Returns a None constant.
        disabled_inference_mode_forcibly = False
        if (
            torch._dynamo.config.fake_tensor_disable_inference_mode
            and self.target_values[0]
        ):
            # Do not set the inference mode because we keep it off during
            # compilation. Set the grad_enabled to False to reflect the relevant
            # part of inference_mode to torch.compile.
            disabled_inference_mode_forcibly = True
            prior = torch.is_grad_enabled()
            torch._C._set_grad_enabled(False)
        else:
            ctx = torch.autograd.grad_mode._enter_inference_mode(*self.target_values)

        def cleanup_hook() -> None:
            # [FUNCTION DOC] HELPER: undo enter: restore the prior grad mode if
            # inference mode was forcibly skipped, else exit inference mode.
            if disabled_inference_mode_forcibly:
                torch._C._set_grad_enabled(prior)
            else:
                torch.autograd.grad_mode._exit_inference_mode(ctx)

        self.set_cleanup_hook(tx, cleanup_hook)
        self.proxy = tx.output.create_node(
            "call_function",
            torch.autograd.grad_mode._enter_inference_mode,
            (*self.target_values,),
            {},
        )
        return variables.ConstantVariable.create(None)

    def module_name(self) -> str:
        # [FUNCTION DOC] Module used when reconstructing: torch.
        return "torch"

    def fn_name(self) -> str:
        # [FUNCTION DOC] Reconstruction name: inference_mode.
        return "inference_mode"

    def python_type(self) -> type:
        # [FUNCTION DOC] The Python type reported: the inference_mode class.
        return torch.inference_mode


class GenericDeviceVariable(ContextWrappingVariable):
    # [CLASS DOC] Abstract base for device context managers that swap the active
    # device index. Subclasses set three class-level callables: the exchange
    # function (switch device, return the previous index), the maybe-exchange
    # function (switch back) and a device-to-index conversion. Enter swaps and
    # emits a graph node; exit emits a graph node swapping back.
    """Abstract base for device context managers that swap the active device index."""

    _exchange_fn: Any
    _maybe_exchange_fn: Any
    _get_device_index_fn: Any

    @classmethod
    def create(
        cls, tx: "InstructionTranslatorBase", device: Any, **kwargs: Any
    ) -> "GenericDeviceVariable":
        # [FUNCTION DOC] Factory: converts the device to an optional device index
        # with the class-specific function and uses it as the sole target value.
        return cls(
            target_values=[cls._get_device_index_fn(device, optional=True)],
            initial_values=None,
            **kwargs,
        )

    def exit(
        self, tx: "InstructionTranslatorBase", *args: VariableTracker
    ) -> VariableTracker:
        # [FUNCTION DOC] Run the pending cleanup (assert it exists) and add a graph
        # node that switches back using the node produced by enter. Returns a False
        # constant (the exception is never suppressed).
        self.cleanup_assert()
        tx.output.create_node(
            "call_function",
            self._maybe_exchange_fn,
            (self.proxy,),
            {},
        )
        return variables.ConstantVariable.create(False)

    def enter(self, tx: "InstructionTranslatorBase") -> VariableTracker:
        # [FUNCTION DOC] Switch device eagerly to the target index (remembering the
        # previous index), register cleanup switching back, and add a graph node
        # performing the switch. Returns a None constant.
        prev_idx = self._exchange_fn(*self.target_values)
        self.set_cleanup_hook(tx, lambda: self._maybe_exchange_fn(prev_idx))
        self.proxy = tx.output.create_node(
            "call_function",
            self._exchange_fn,
            (*self.target_values,),
            {},
        )
        return variables.ConstantVariable.create(None)

    def module_name(self) -> str:
        # [FUNCTION DOC] Must be overridden by subclasses; base raises
        # NotImplementedError.
        raise NotImplementedError

    def fn_name(self) -> str:
        # [FUNCTION DOC] Reconstruction name: device.
        return "device"

    def python_type(self) -> type:
        # [FUNCTION DOC] Must be overridden by subclasses; base raises
        # NotImplementedError.
        raise NotImplementedError


