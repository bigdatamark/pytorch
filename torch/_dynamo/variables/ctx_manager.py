# [MODULE DOC] Dynamo variable trackers for context managers. Defines the base
# ContextWrappingVariable (enter/exit protocol, cleanup hooks, wrapping of
# decorated functions, reconstruction support) and many subclasses modelling
# torch state managers: grad mode, inference mode, forward AD, functorch
# grad/jvp/vmap nesting, autocast, device switching (cuda/xpu/accelerator),
# torch-function disabling, saved-tensor hooks, profiler contexts, SDPA kernel
# selection, FSDP training state, dynamo config patching, cudagraph override,
# fx traceback annotation, warnings capture, nullcontext, plus the
# WithEnterFunctionVariable / WithExitFunctionVariable helpers used by the
