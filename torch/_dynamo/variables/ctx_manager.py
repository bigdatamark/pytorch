class DualLevelContextManager(ContextWrappingVariable):
    # [CLASS DOC] Models the forward-AD dual level context manager. A shared
    # guard (dual level) is installed on enter. Enter creates a new dual level
    # (kept in new_level) and emits a graph node; exit leaves that level.
    """Represents torch.autograd.forward_ad.dual_level ctx manager"""

    _guards_singleton = Guard(GlobalStateSource(), GuardBuilder.DUAL_LEVEL)  # type: ignore[arg-type]

    @staticmethod
    def create(
        tx: "InstructionTranslatorBase", **kwargs: Any
    ) -> "DualLevelContextManager":
        # [FUNCTION DOC] Factory: no target or initial values.
        return DualLevelContextManager(
            target_values=None,
            initial_values=None,
            **kwargs,
        )

    def enter(self, tx: "InstructionTranslatorBase") -> VariableTracker:
        # [FUNCTION DOC] Install the dual level guard, enter a dual level eagerly
        # (saved in new_level), register cleanup exiting it, add a graph node
        # entering the level, and return the level as a variable.
        install_guard(self._guards_singleton)
        self.new_level = torch.autograd.forward_ad.enter_dual_level()
        self.set_cleanup_hook(
            tx, lambda: torch.autograd.forward_ad.exit_dual_level(level=self.new_level)
        )
        self.proxy = tx.output.create_node(
            "call_function",
            torch._functorch.predispatch._enter_dual_level,
            (),
            {},
        )
        return variables.VariableTracker.build(tx, self.new_level)

    def exit(
        self, tx: "InstructionTranslatorBase", *args: VariableTracker
    ) -> VariableTracker:
        # [FUNCTION DOC] Run cleanup and add a graph node exiting the recorded
        # dual level. Returns a None constant.
        self.cleanup()
        tx.output.create_node(
            "call_function",
            torch._functorch.predispatch._exit_dual_level,
            (),
            {"level": self.new_level},
        )
        return variables.ConstantVariable.create(None)

