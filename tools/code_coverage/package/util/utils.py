# [MODULE DOC] General helpers for the code coverage tool: time formatting, logging to the log
# file in LOG_DIR, file and folder management, path manipulation, compiler/platform/test-type
# validation and compiler detection. No import-time side effects.
from __future__ import annotations

import os
import shutil
import sys
import time
from typing import Any, NoReturn

from .setting import (
    CompilerType,
    LOG_DIR,
    PROFILE_DIR,
    TestList,
    TestPlatform,
    TestType,
)


def convert_time(seconds: float) -> str:
    # [FUNCTION DOC] Formats a duration in seconds as hours:minutes:seconds text with two digit
    # minutes and seconds. The value is rounded to whole seconds and wrapped modulo one day.
    seconds = int(round(seconds))
    seconds = seconds % (24 * 3600)
    hour = seconds // 3600
    seconds %= 3600
    minutes = seconds // 60
    seconds %= 60

    return f"{hour:d}:{minutes:02d}:{seconds:02d}"


def print_time(message: str, start_time: float, summary_time: bool = False) -> None:
    # [FUNCTION DOC] Appends a line to the log file with the message and the time elapsed since
    # start_time (formatted by convert_time); when summary_time is true also appends a blank
    # separator. Side effect: opens LOG_DIR/log.txt, which must exist, otherwise an OSError.
    with open(os.path.join(LOG_DIR, "log.txt"), "a+") as log_file:
        end_time = time.time()
        print(message, convert_time(end_time - start_time), file=log_file)
        if summary_time:
            print("\n", file=log_file)


def print_log(*args: Any) -> None:
    # [FUNCTION DOC] Appends a line prefixed with the log tag to the log file, joining the
    # arguments with spaces. All arguments must be strings, otherwise a TypeError is raised.
    # Writes to LOG_DIR/log.txt, not to the console.
    with open(os.path.join(LOG_DIR, "log.txt"), "a+") as log_file:
        print(f"[LOG] {' '.join(args)}", file=log_file)


def print_error(*args: Any) -> None:
    # [FUNCTION DOC] Same as print_log but with the error tag: appends a line to the log file
    # joining the string arguments with spaces. Nothing is printed to the console or raised
    # beyond TypeError for non-string arguments.
    with open(os.path.join(LOG_DIR, "log.txt"), "a+") as log_file:
        print(f"[ERROR] {' '.join(args)}", file=log_file)


def remove_file(path: str) -> None:
    # [FUNCTION DOC] Deletes the file at path if it exists; does nothing otherwise.
    if os.path.exists(path):
        os.remove(path)


def remove_folder(path: str) -> None:
    # [FUNCTION DOC] Recursively deletes the folder at path; raises an error if it is missing.
    shutil.rmtree(path)


def create_folder(*paths: Any) -> None:
    # [FUNCTION DOC] Creates each given folder, including parents; existing folders are fine.
    for path in paths:
        os.makedirs(path, exist_ok=True)


# clean up all the files generated by coverage tool
def clean_up() -> None:
    # [FUNCTION DOC] Deletes the whole profile folder and then exits the process through
    # sys.exit with a success message (raises SystemExit; never returns normally).
    # remove profile folder
    remove_folder(PROFILE_DIR)
    sys.exit("Clean Up Successfully!")


def convert_to_relative_path(whole_path: str, base_path: str) -> str:
    # [FUNCTION DOC] Returns whole_path with the base_path prefix and the following separator
    # removed. Raises RuntimeError if base_path does not occur in whole_path.
    # KNOWN ISSUE: only checks containment, not that base_path is a prefix, so a base found in
    # the middle yields a wrongly sliced result.
    # ("profile/raw", "profile") -> "raw"
    if base_path not in whole_path:
        raise RuntimeError(base_path + " is not in " + whole_path)
    return whole_path[len(base_path) + 1 :]


def replace_extension(filename: str, ext: str) -> str:
    # [FUNCTION DOC] Returns filename with everything from its last dot replaced by ext (which
    # should include the dot). KNOWN ISSUE: if there is no dot, the last character is dropped.
    return filename[: filename.rfind(".")] + ext


# a file is related if it's in one of the test_list folder
def related_to_test_list(file_name: str, test_list: TestList) -> bool:
    # [FUNCTION DOC] Returns true if the name of any test in test_list is a substring of
    # file_name, false otherwise.
    for test in test_list:
        if test.name in file_name:
            return True
    return False


def get_raw_profiles_folder() -> str:
    # [FUNCTION DOC] Returns the raw profiles folder: the RAW_PROFILES_FOLDER environment
    # variable when set, otherwise the raw subfolder of the profile directory.
    return os.environ.get("RAW_PROFILES_FOLDER", os.path.join(PROFILE_DIR, "raw"))


def detect_compiler_type(platform: TestPlatform) -> CompilerType:
    # [FUNCTION DOC] Asks the platform specific helper (OSS or fbcode, imported lazily) which
    # compiler produced the coverage data, validates it with check_compiler_type (which raises
    # on anything but clang or gcc) and returns it.
    if platform == TestPlatform.OSS:
        from package.oss.utils import (  # type: ignore[assignment, import, misc]
            detect_compiler_type,
        )

        cov_type = detect_compiler_type()  # type: ignore[call-arg]
    else:
        from caffe2.fb.code_coverage.tool.package.fbcode.utils import (  # type: ignore[import]
            detect_compiler_type,
        )

        cov_type = detect_compiler_type()

    check_compiler_type(cov_type)
    return cov_type  # type: ignore[no-any-return]


def get_test_name_from_whole_path(path: str) -> str:
    # [FUNCTION DOC] Extracts the test name from a path: the text between the last slash and
    # the last dot. Raises AssertionError if the path has no slash or no dot.
    # KNOWN ISSUE: a dot only in a directory name before the last slash gives an empty or wrong
    # slice.
    # code_coverage_tool/profile/merged/haha.merged -> haha
    start = path.rfind("/")
    end = path.rfind(".")
    if not (start >= 0 and end >= 0):
        raise AssertionError(f"Invalid path format: {path}")
    return path[start + 1 : end]


def check_compiler_type(cov_type: CompilerType | None) -> None:
    # [FUNCTION DOC] Returns silently if cov_type is gcc or clang; otherwise raises a generic
    # Exception telling the user to set the COMPILER_TYPE environment variable.
    if cov_type is not None and cov_type in [CompilerType.GCC, CompilerType.CLANG]:
        return
    raise Exception(  # noqa: TRY002
        f"Can't parse compiler type: {cov_type}.",
        " Please set environment variable COMPILER_TYPE as CLANG or GCC",
    )


def check_platform_type(platform_type: TestPlatform) -> None:
    # [FUNCTION DOC] Returns silently for the OSS or FBCODE platform; otherwise raises a
    # generic Exception. KNOWN ISSUE: the message tells the user to set COMPILER_TYPE, but
    # the platform is not selected by that variable.
    if platform_type in [TestPlatform.OSS, TestPlatform.FBCODE]:
        return
    raise Exception(  # noqa: TRY002
        f"Can't parse platform type: {platform_type}.",
        " Please set environment variable COMPILER_TYPE as OSS or FBCODE",
    )


def check_test_type(test_type: str, target: str) -> None:
    # [FUNCTION DOC] Returns silently if test_type equals the value of a known TestType (C++
    # or Python); otherwise raises a generic Exception naming the buck target to check.
    if test_type in [TestType.CPP.value, TestType.PY.value]:
        return
    raise Exception(  # noqa: TRY002
        f"Can't parse test type: {test_type}.",
        f" Please check the type of buck target: {target}",
    )


def raise_no_test_found_exception(
    cpp_binary_folder: str, python_binary_folder: str
) -> NoReturn:
    # [FUNCTION DOC] Always raises RuntimeError saying no C++ or Python tests were found in the
    # two given binary folders.
    raise RuntimeError(
        f"No cpp and python tests found in folder **{cpp_binary_folder} and **{python_binary_folder}**"
    )
