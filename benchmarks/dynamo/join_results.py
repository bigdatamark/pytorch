# [MODULE DOC] Command line tool that joins several benchmark result csv files on the name
# column into one csv, one column per input file, dropping benchmarks that failed everywhere.
# No import-time side effects beyond imports (pandas required).
"""
A tool to merge multiple csv files (generated by torchbench.py/etc) into a single csv file.
Performs an outer join based on the benchmark name, filling in any missing data with zeros.
"""

import argparse
import functools
import operator
from pathlib import Path

import pandas as pd


def longest_common_prefix(strs):
    # [FUNCTION DOC] Return the longest string prefix shared by all given strings. Returns an
    # empty string if there is none. Raises ValueError for an empty list.
    # KNOWN ISSUE: if the shortest string is itself a prefix of all the others the loop ends
    # without returning it and the result is an empty string rather than that prefix.
    shortest_str = min(strs, key=len)
    for i, char in enumerate(shortest_str):
        for other in strs:
            if other[i] != char:
                return shortest_str[:i]
    return ""


def main():
    # [FUNCTION DOC] Entry point. Reads each input csv, keeps the name column and the chosen
    # field (default speedup), naming the column after the part of the file stem following the
    # common stem prefix. Outer-merges all frames on name, fills missing values with zero, drops
    # rows where every column is zero, and writes a csv (to the output option, or to a file
    # named from the stripped common prefix or "output") without an index. Prints the path.
    # Assumes at least one input; with none the prefix helper raises ValueError.
    parser = argparse.ArgumentParser()
    parser.add_argument("--field", "-f", default="speedup", type=str)
    parser.add_argument("--output", "-o", type=str)
    parser.add_argument("inputs", nargs="*")
    args = parser.parse_args()

    prefix = longest_common_prefix([Path(inp).stem for inp in args.inputs])
    frames = []
    fields = []
    for inp in args.inputs:
        field = Path(inp).stem[len(prefix) :]
        fields.append(field)
        frames.append(
            pd.read_csv(inp)
            .filter(["name", args.field])
            .rename(columns={args.field: field})
        )

    df = frames[0]
    for other in frames[1:]:
        df = df.merge(other, how="outer", on="name")
    df = df.fillna(0)

    # drop rows where all backends failed
    df = df[functools.reduce(operator.or_, [df[f] != 0 for f in fields])]

    prefix = prefix.strip("_") or "output"
    output = args.output or f"{prefix}.csv"
    print(f"Writing {output}")
    df.to_csv(output, index=False)


if __name__ == "__main__":
    main()
