# [MODULE DOC] Mypy plugin that improves typing of sympy: gives sympy Basic.free_symbols the
# type of a set of Symbol, and defines hook code to add the is_<assumption> boolean-or-None
# attributes (the base class hook is not effective). Import-time side effects: none.
from mypy.plugin import Plugin
from mypy.plugins.common import add_attribute_to_class
from mypy.types import NoneType, UnionType


class SympyPlugin(Plugin):
    # [CLASS DOC] Mypy plugin customizing analysis of sympy classes via a base class hook and
    # an attribute hook. Stateless beyond the base Plugin.
    def get_base_class_hook(self, fullname: str):
        # [FUNCTION DOC] Returns the add_assumptions hook for classes deriving from
        # sympy.core.basic.Basic, else None.
        # KNOWN ISSUE: per the TODO below, this reportedly never worked.
        # TODO: This apparently never worked
        if fullname == "sympy.core.basic.Basic":
            return add_assumptions
        return None

    def get_attribute_hook(self, fullname: str):
        # [FUNCTION DOC] For the attribute sympy.core.basic.Basic.free_symbols returns a hook
        # that types it as a builtins set of sympy.Symbol; returns None for other attributes.
        if fullname == "sympy.core.basic.Basic.free_symbols":
            return lambda ctx: ctx.api.named_generic_type(
                "builtins.set", [ctx.api.named_type("sympy.Symbol")]
            )
        return None


def add_assumptions(ctx) -> None:
    # [FUNCTION DOC] HELPER: Base class hook body. Adds an attribute named is_ followed by each
    # sympy assumption name to the class in ctx, typed as bool or None, using the hard-coded
    # assumption list. Mutates mypy's class info.
    # Generated by list(sys.modules['sympy.core.assumptions']._assume_defined)
    # (do not import sympy to speedup mypy plugin load time)
    assumptions = [
        "hermitian",
        "prime",
        "noninteger",
        "negative",
        "antihermitian",
        "infinite",
        "finite",
        "irrational",
        "extended_positive",
        "nonpositive",
        "odd",
        "algebraic",
        "integer",
        "rational",
        "extended_real",
        "nonnegative",
        "transcendental",
        "extended_nonzero",
        "extended_negative",
        "composite",
        "complex",
        "imaginary",
        "nonzero",
        "zero",
        "even",
        "positive",
        "polar",
        "extended_nonpositive",
        "extended_nonnegative",
        "real",
        "commutative",
    ]
    for a in assumptions:
        add_attribute_to_class(
            ctx.api,
            ctx.cls,
            f"is_{a}",
            UnionType([ctx.api.named_type("builtins.bool"), NoneType()]),
        )


def plugin(version: str):
    # [FUNCTION DOC] Mypy plugin entry point; ignores the version and returns SympyPlugin.
    return SympyPlugin
