# Owner(s): ["oncall: package/deploy"]
# [MODULE DOC] Tests for name mangling in torch.package, which gives modules loaded from a
# package unique prefixed names so they do not shadow regular modules: mangler uniqueness,
# consistency, demangling, prefix extraction and the effect on loaded class module names. Falls
# back to a non-relative import of the shared base test case. Run as a script, it starts the
# test runner.

from io import BytesIO

from torch.package import PackageExporter, PackageImporter
from torch.package._mangling import (
    demangle,
    get_mangle_prefix,
    is_mangled,
    PackageMangler,
)
from torch.testing._internal.common_utils import run_tests


try:
    from .common import PackageTestCase
except ImportError:
    # Support the case where we run this file directly.
    from common import PackageTestCase


class TestMangling(PackageTestCase):
    # [CLASS DOC] Test case for the mangler class and the module-level mangling helpers.
    def test_unique_manglers(self):
        # [FUNCTION DOC] Two separate manglers must mangle the same name to different results.
        """
        Each mangler instance should generate a unique mangled name for a given input.
        """
        a = PackageMangler()
        b = PackageMangler()
        self.assertNotEqual(a.mangle("foo.bar"), b.mangle("foo.bar"))

    def test_mangler_is_consistent(self):
        # [FUNCTION DOC] One mangler must return the same result when mangling the same
        # name twice.
        """
        Mangling the same name twice should produce the same result.
        """
        a = PackageMangler()
        self.assertEqual(a.mangle("abc.def"), a.mangle("abc.def"))

    def test_roundtrip_mangling(self):
        # [FUNCTION DOC] Demangling a mangled simple name must return the original name.
        a = PackageMangler()
        self.assertEqual("foo", demangle(a.mangle("foo")))

    def test_is_mangled(self):
        # [FUNCTION DOC] Names mangled by either of two manglers are reported as mangled, while
        # a plain name and a demangled name are not.
        a = PackageMangler()
        b = PackageMangler()
        self.assertTrue(is_mangled(a.mangle("foo.bar")))
        self.assertTrue(is_mangled(b.mangle("foo.bar")))

        self.assertFalse(is_mangled("foo.bar"))
        self.assertFalse(is_mangled(demangle(a.mangle("foo.bar"))))

    def test_demangler_multiple_manglers(self):
        # [FUNCTION DOC] The module-level demangle function must undo mangling done by any
        # mangler instance, returning the original dotted names.
        """
        PackageDemangler should be able to demangle name generated by any PackageMangler.
        """
        a = PackageMangler()
        b = PackageMangler()

        self.assertEqual("foo.bar", demangle(a.mangle("foo.bar")))
        self.assertEqual("bar.foo", demangle(b.mangle("bar.foo")))

    def test_mangle_empty_errors(self):
        # [FUNCTION DOC] Mangling the empty string must raise AssertionError.
        a = PackageMangler()
        with self.assertRaises(AssertionError):
            a.mangle("")

    def test_demangle_base(self):
        # [FUNCTION DOC] Takes the mangle parent (the part before the first dot of a mangled
        # name) and checks that demangling it yields the empty string.
        """
        Demangling a mangle parent directly should currently return an empty string.
        """
        a = PackageMangler()
        mangled = a.mangle("foo")
        mangle_parent = mangled.partition(".")[0]
        self.assertEqual("", demangle(mangle_parent))

    def test_mangle_prefix(self):
        # [FUNCTION DOC] Checks that the prefix returned for a mangled name, joined by a dot to
        # the original name, reconstructs the mangled name.
        a = PackageMangler()
        mangled = a.mangle("foo.bar")
        mangle_prefix = get_mangle_prefix(mangled)
        self.assertEqual(mangle_prefix + "." + "foo.bar", mangled)

    def test_unique_module_names(self):
        # [FUNCTION DOC] Pickles an object of a regular fixture class into a package and loads
        # it through two importers on the same buffer. Checks the loaded classes have a
        # different module name from the original and from each other, so loaded modules never
        # shadow others.
        import package_a.subpackage

        obj = package_a.subpackage.PackageASubpackageObject()
        obj2 = package_a.PackageAObject(obj)
        f1 = BytesIO()
        with PackageExporter(f1) as pe:
            pe.intern("**")
            pe.save_pickle("obj", "obj.pkl", obj2)
        f1.seek(0)
        importer1 = PackageImporter(f1)
        loaded1 = importer1.load_pickle("obj", "obj.pkl")
        f1.seek(0)
        importer2 = PackageImporter(f1)
        loaded2 = importer2.load_pickle("obj", "obj.pkl")

        # Modules from loaded packages should not shadow the names of modules.
        # See mangling.md for more info.
        self.assertNotEqual(type(obj2).__module__, type(loaded1).__module__)
        self.assertNotEqual(type(loaded1).__module__, type(loaded2).__module__)

    def test_package_mangler(self):
        # [FUNCTION DOC] A mangler demangles a name it produced back to the original, but leaves
        # a name mangled by a different mangler unchanged.
        a = PackageMangler()
        b = PackageMangler()
        a_mangled = a.mangle("foo.bar")
        # Since `a` mangled this string, it should demangle properly.
        self.assertEqual(a.demangle(a_mangled), "foo.bar")
        # Since `b` did not mangle this string, demangling should leave it alone.
        self.assertEqual(b.demangle(a_mangled), a_mangled)


if __name__ == "__main__":
    run_tests()
